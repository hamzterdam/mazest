function normalize(value) {
  return value
    .toLocaleLowerCase("tr")
    .replace(/ı/g, "i")
    .replace(/İ/g, "i")
    .normalize("NFC")
    .trim()
    .replace(/\s+/g, " ");
}

function sourcePriority(entry) {
  const explicitPriority = Number(entry.priority);
  if (Number.isFinite(explicitPriority)) return explicitPriority;

  const source = String(entry.source || "");
  if (source.includes("User-provided current dictionary")) return 10;
  if (source.includes("User-provided prototype")) return 8;
  if (source.includes("Ma'z Êst cleaned")) return 6;
  if (source.includes("Bimus")) return 4;
  return 1;
}

function mergeLexicon(entries) {
  const merged = new Map();

  entries.forEach((entry) => {
    if (!entry?.tr || !entry?.zazaki) return;
    const key = normalize(entry.tr);
    if (!key) return;

    const cleanEntry = {
      ...entry,
      tr: String(entry.tr).trim(),
      zazaki: String(entry.zazaki).trim(),
      alternatives: [...new Set((entry.alternatives || []).map((alt) => String(alt).trim()).filter(Boolean))],
      source: entry.source || "Unspecified source",
      priority: sourcePriority(entry)
    };
    const existing = merged.get(key);

    if (!existing) {
      merged.set(key, cleanEntry);
      return;
    }

    if (cleanEntry.priority > (existing.priority || 0)) {
      const alternatives = [
        existing.zazaki,
        ...(existing.alternatives || []),
        ...cleanEntry.alternatives
      ].filter((alt) => alt && alt !== cleanEntry.zazaki);

      merged.set(key, {
        ...cleanEntry,
        alternatives: [...new Set(alternatives)],
        verified: cleanEntry.verified || existing.verified,
        source: String(existing.source).includes(cleanEntry.source)
          ? existing.source
          : `${cleanEntry.source} + ${existing.source}`
      });
      return;
    }

    if (existing.zazaki !== cleanEntry.zazaki && !existing.alternatives.includes(cleanEntry.zazaki)) {
      existing.alternatives.push(cleanEntry.zazaki);
    }
    cleanEntry.alternatives.forEach((alt) => {
      if (alt !== existing.zazaki && !existing.alternatives.includes(alt)) existing.alternatives.push(alt);
    });
    existing.verified = existing.verified || cleanEntry.verified;
    existing.category = existing.category || cleanEntry.category;
    existing.dialect = existing.dialect || cleanEntry.dialect;
    if (!String(existing.source).includes(cleanEntry.source)) {
      existing.source = `${existing.source} + ${cleanEntry.source}`;
    }
  });

  return [...merged.values()];
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function capFirst(value) {
  return value ? value.charAt(0).toLocaleUpperCase("tr") + value.slice(1) : value;
}

function translateFragment(text) {
  const normalized = normalize(text).replace(/[?.!,;:]+$/g, "");
  const exactPhrase = phraseMap.get(normalized);
  if (exactPhrase) {
    return { text: exactPhrase.zazaki, matched: 1, total: 1, alternatives: collectAlternatives([exactPhrase]), missing: [] };
  }

  let working = text;
  const placeholders = [];
  const phraseEntries = [...phraseMap.values()].sort((a, b) => b.tr.length - a.tr.length);
  phraseEntries.forEach((entry) => {
    const re = new RegExp(`\\b${escapeRegExp(entry.tr)}\\b`, "giu");
    working = working.replace(re, () => {
      const marker = `__PHRASE_${placeholders.length}__`;
      placeholders.push(entry);
      return marker;
    });
  });

  const tokens = working.match(/__PHRASE_\d+__|[\p{L}'’]+|[0-9]+|[^\s\p{L}0-9]/giu) || [];
  let matched = 0;
  let total = 0;
  const used = [];
  const missing = [];
  const translated = tokens.map((token) => {
    const placeholderMatch = token.match(/^__PHRASE_(\d+)__$/);
    if (placeholderMatch) {
      const entry = placeholders[Number(placeholderMatch[1])];
      matched += 1;
      total += 1;
      used.push(entry);
      return entry.zazaki;
    }
    if (/^[\p{L}'’]+$/u.test(token)) {
      total += 1;
      const entry = wordMap.get(normalize(token));
      if (entry) {
        matched += 1;
        used.push(entry);
        return entry.zazaki;
      }
      missing.push(token);
    }
    return token;
  });

  return {
    text: tidySpacing(translated.join(" ")),
    matched,
    total: Math.max(total, 1),
    alternatives: collectAlternatives(used),
    missing: [...new Set(missing.map(normalize))].filter(Boolean).slice(0, 8)
  };
}

function collectAlternatives(entries) {
  return entries
    .filter((entry) => entry.alternatives?.length)
    .map((entry) => `${entry.tr}: ${entry.zazaki} / ${entry.alternatives.join(", ")}`)
    .slice(0, 8);
}

function tidySpacing(value) {
  return value
    .replace(/\s+([?.!,;:])/g, "$1")
    .replace(/([¿¡])\s+/g, "$1")
    .replace(/\s{2,}/g, " ")
    .trim();
}

function translateText(text) {
  const clean = text.trim();
  if (!clean) return { text: "", matched: 0, total: 1, alternatives: [], missing: [] };

  const exactPhraseKey = normalize(clean).replace(/[?.!,;:]+$/g, "");
  if (phraseMap.has(exactPhraseKey)) {
    return translateFragment(clean);
  }

  for (const rule of grammarRules) {
    const match = clean.match(rule.pattern);
    if (match) {
      const result = translateFragment(match[1]);
      return {
        text: tidySpacing(rule.apply(match)),
        matched: result.matched + 1,
        total: result.total + 1,
        alternatives: result.alternatives,
        missing: result.missing,
        rule: rule.name
      };
    }
  }

  return translateFragment(clean);
}

function render() {
  const result = translateText(input.value);
  output.textContent = result.text || (currentUiLang === "za" ? "Çarnayış ıta aseno." : currentUiLang === "ku" ? "Werger li vir xuya dibe." : "Translation will appear here.");
  charCount.textContent = `${input.value.length} / 1000`;
  const score = Math.round((result.matched / Math.max(result.total, 1)) * 100);
  confidenceBar.style.width = `${Math.max(score, result.text ? 12 : 0)}%`;
  const matchedLabel = currentUiLang === "za" ? "eşbena" : currentUiLang === "ku" ? "lihevhat" : "matched";
  confidenceLabel.textContent = result.text
    ? `${score}% ${matchedLabel}${result.rule ? ` · ${result.rule}` : ""}`
    : uiCopy[currentUiLang]?.confidence || "Rule-based beta";
  renderAnalysis(result);
}

function renderAnalysis(result) {
  const labels = {
    en: ["total entries", "Bimus/user examples", "phrase patterns", "grammar models", "Alt", "Needs review"],
    ku: ["têketin", "mînakên Bimus/user", "modelên hevokan", "modelên rêzimanê", "Alternatîf", "Pêdivî bi kontrolê"],
    za: ["têketışî", "mînakê Bimus/user", "modelê hevokan", "modelê gramêrî", "Alternatîf", "Şîrove lazim"]
  }[currentUiLang] || ["total entries", "Bimus/user examples", "phrase patterns", "grammar models", "Alt", "Needs review"];
  const chips = [];
  chips.push(`<span>${lexicon.length} ${labels[0]}</span>`);
  chips.push(`<span>${importedLexicon.length} ${labels[1]}</span>`);
  chips.push(`<span>${[...phraseMap.keys()].length} ${labels[2]}</span>`);
  chips.push(`<span>${grammarRules.length} ${labels[3]}</span>`);
  result.alternatives.forEach((alt) => chips.push(`<span class="alt">${labels[4]}: ${alt}</span>`));
  result.missing.forEach((word) => chips.push(`<span class="miss">${labels[5]}: ${word}</span>`));
  analysisPanel.innerHTML = chips.join("");
}

function setLanguage(lang, persist = true) {
  currentUiLang = lang;
  const dictionary = uiCopy[lang] || uiCopy.en;
  document.documentElement.lang = lang === "za" ? "zza" : lang;
  document.querySelectorAll("[data-copy]").forEach((el) => {
    const key = el.dataset.copy;
    el.textContent = dictionary[key] || uiCopy.en[key] || el.textContent;
  });
  document.querySelectorAll("[data-copy-placeholder]").forEach((el) => {
    const key = el.dataset.copyPlaceholder;
    const value = dictionary[key] || uiCopy.en[key];
    if (value) el.setAttribute("placeholder", value);
  });
  document.querySelectorAll("[data-ui-lang]").forEach((button) => {
    button.classList.toggle("active", button.dataset.uiLang === lang);
  });
  if (persist) localStorage.setItem("mazestTranslatorLang", lang);
  render();
}

