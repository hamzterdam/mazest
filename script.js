const languageButtons = document.querySelectorAll("[data-lang]");
const navToggle = document.querySelector(".nav-toggle");
const nav = document.querySelector(".main-nav");
const subscribeForm = document.querySelector(".site-footer form");
const contactForm = document.querySelector(".contact-form");

function setLanguage(lang) {
  const dictionary = translations[lang] || translations.en;
  document.documentElement.lang = lang === "za" ? "zza" : lang;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = dictionary[node.dataset.i18n] || translations.en[node.dataset.i18n];
    if (value) node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const value = dictionary[node.dataset.i18nPlaceholder] || translations.en[node.dataset.i18nPlaceholder];
    if (value) node.setAttribute("placeholder", value);
  });

  languageButtons.forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });

  localStorage.setItem("mazest-language", lang);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

navToggle.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("open");
  document.body.classList.toggle("menu-open", isOpen);
  navToggle.setAttribute("aria-expanded", String(isOpen));
});

nav.addEventListener("click", (event) => {
  if (event.target.matches("a")) {
    nav.classList.remove("open");
    document.body.classList.remove("menu-open");
    navToggle.setAttribute("aria-expanded", "false");
  }
});

document.querySelectorAll(".tabs button").forEach((button) => {
  button.addEventListener("click", () => {
    document.querySelectorAll(".tabs button").forEach((item) => item.classList.remove("active"));
    button.classList.add("active");
  });
});

subscribeForm?.addEventListener("submit", (event) => {
  event.preventDefault();
  const email = new FormData(subscribeForm).get("email") || "";
  const subject = encodeURIComponent("Subscribe to Ma'z Êst");
  const body = encodeURIComponent(`Please add this email to the Ma'z Êst mailing list:\n\n${email}`);
  window.location.href = `mailto:mazestfr@gmail.com?subject=${subject}&body=${body}`;
  subscribeForm.reset();
});

contactForm?.addEventListener("submit", (event) => {
  event.preventDefault();
  const formData = new FormData(contactForm);
  const name = formData.get("name") || "";
  const email = formData.get("email") || "";
  const message = formData.get("message") || "";
  const subject = encodeURIComponent(`Message Ma'z Êst - ${name}`);
  const body = encodeURIComponent(`Name: ${name}\nEmail: ${email}\n\n${message}`);
  window.location.href = `mailto:mazestfr@gmail.com?subject=${subject}&body=${body}`;
  contactForm.reset();
});

setLanguage(localStorage.getItem("mazest-language") || "en");
